// Syntax / Keyword         Kaam                                      Example

// switch                   Ek value ko multiple cases se compare     switch(day)

// case                     Specific value match karta hai             case 1:

// break                    Matching case ke baad switch rokta hai    break;

// default                  Koi case match na ho to chalta hai         default:

// switch...case             Multiple fixed values check karta hai      switch(choice)

